/**
 * GCode Validation Utilities for E2E Tests
 *
 * Reusable validators for single-color, multi-color, and multi-object plate
 * GCode output. Based on patterns from slice-cube-e2e.mjs and
 * fi-mini-multicolor-e2e.mjs.
 *
 * Exports:
 *   validateGCode(gcode)                        — basic single-color checks
 *   validateMulticolorGCode(gcode, expected)     — multi-color + tool change checks
 *   validatePlateGCode(gcode, expectedObjects)   — multi-object plate checks
 *   analyzeMulticolorGCode(gcode)                — raw per-extruder XY/Z bounds
 */

/**
 * Validate single-color GCode output.
 *
 * Checks: has content (>10 lines), G0/G1 moves, extrusion (E param),
 * layer changes (;LAYER_CHANGE or Z moves), Z range, temperature (M104/M109),
 * fan commands (M106/M107), slicer signature.
 *
 * @param {string} gcode - Raw GCode string
 * @param {object} [options] - Optional validation parameters
 * @param {number} [options.expectedMinZ] - Expected minimum Z height (mm)
 * @param {number} [options.expectedMaxZ] - Expected maximum Z height (mm)
 * @param {number} [options.zTolerance=5] - Tolerance for Z range checks (mm)
 * @returns {{ passed: boolean, checks: Array<{name: string, passed: boolean, detail: string}>, stats: object }}
 */
export function validateGCode(gcode, options = {}) {
  const { expectedMinZ, expectedMaxZ, zTolerance = 5 } = options;
  const lines = gcode.split('\n');
  const checks = [];
  let passed = true;

  function check(name, ok, detail) {
    checks.push({ name, passed: ok, detail });
    if (!ok) passed = false;
  }

  // Check 1: Has content
  const hasContent = lines.length > 10;
  check('has_content', hasContent, `${lines.length} lines`);

  // Check 2: Has G0/G1 move commands
  const moveLines = lines.filter(l => /^G[01]\s/.test(l));
  check('has_moves', moveLines.length > 0, `${moveLines.length} G0/G1 commands`);

  // Check 3: Has extrusion (E parameter on G1 commands)
  const extrusionLines = lines.filter(l => /^G1\s.*E[\d.]+/.test(l));
  check('has_extrusion', extrusionLines.length > 0, `${extrusionLines.length} extrusion moves`);

  // Check 4: Has layer changes
  const layerComments = lines.filter(l => /^;LAYER_CHANGE/.test(l));
  const zMoves = lines.filter(l => /^G[01]\s.*Z[\d.]+/.test(l));
  check('has_layers', layerComments.length > 0 || zMoves.length > 0,
    `${layerComments.length} layer comments, ${zMoves.length} Z moves`);

  // Check 5: Z range
  const zValues = [];
  for (const l of lines) {
    const m = l.match(/;Z:([\d.]+)/);
    if (m) zValues.push(parseFloat(m[1]));
  }
  if (zValues.length === 0) {
    for (const l of lines) {
      const m = l.match(/^G[01]\s.*Z([\d.]+)/);
      if (m) zValues.push(parseFloat(m[1]));
    }
  }
  const maxZ = zValues.length > 0 ? zValues.reduce((a, b) => Math.max(a, b)) : 0;
  const minZ = zValues.length > 0 ? zValues.reduce((a, b) => Math.min(a, b)) : 0;

  if (expectedMaxZ !== undefined) {
    const zOk = maxZ >= (expectedMaxZ - zTolerance) && maxZ <= (expectedMaxZ + zTolerance);
    check('z_range_reasonable', zOk,
      `Z range: ${minZ.toFixed(2)}-${maxZ.toFixed(2)}mm (expected ~${expectedMaxZ}mm ±${zTolerance}mm)`);
  } else {
    // Generic: just check Z > 0
    check('z_range_reasonable', maxZ > 0.5, `Z range: ${minZ.toFixed(2)}-${maxZ.toFixed(2)}mm`);
  }

  // Check 6: Has temperature commands
  const tempLines = lines.filter(l => /^M10[49]\s/.test(l));
  check('has_temperature', tempLines.length > 0, `${tempLines.length} temp commands (M104/M109)`);

  // Check 7: Has fan commands
  const fanLines = lines.filter(l => /^M10[67]\s/.test(l));
  checks.push({ name: 'has_fan_commands', passed: fanLines.length > 0, detail: `${fanLines.length} fan commands` });
  // Fan commands are informational — don't fail on missing

  // Check 8: Slicer signature
  const hasSlicerSig = lines.some(l => /generated by PrusaSlicer|generated by OrcaSlicer|; slic3r_pe_/.test(l));
  checks.push({ name: 'slicer_signature', passed: hasSlicerSig,
    detail: hasSlicerSig ? 'Found slicer signature' : 'No slicer signature found' });

  // Parse print stats
  const timeMatch = gcode.match(/; estimated printing time \(normal mode\) = (.+)/);
  const filamentMatch = gcode.match(/; filament used \[mm\] = ([\d.]+)/);

  return {
    passed,
    checks,
    stats: {
      totalLines: lines.length,
      moveCommands: moveLines.length,
      extrusionMoves: extrusionLines.length,
      layerChanges: layerComments.length,
      zRange: { min: minZ, max: maxZ },
      estimatedTime: timeMatch ? timeMatch[1] : null,
      filamentUsedMm: filamentMatch ? parseFloat(filamentMatch[1]) : null,
    },
  };
}

/**
 * Parse GCode and extract per-extruder XY/Z bounds and move counts.
 *
 * @param {string} gcode - Raw GCode string
 * @returns {{ bounds: object, t0Moves: number, t1Moves: number, layerCount: number, t1Layers: number[], toolChanges: number }}
 */
export function analyzeMulticolorGCode(gcode) {
  const lines = gcode.split('\n');
  let currentExtruder = 0;
  let currentX = 0, currentY = 0, currentZ = 0;
  let layerCount = 0;
  let toolChanges = 0;

  // Track bounds for up to 16 extruders
  const extruderBounds = {};
  const extruderMoves = {};
  const extruderLayers = {};

  function ensureExtruder(t) {
    if (!extruderBounds[t]) {
      extruderBounds[t] = {
        minX: Infinity, maxX: -Infinity,
        minY: Infinity, maxY: -Infinity,
        minZ: Infinity, maxZ: -Infinity,
      };
      extruderMoves[t] = 0;
      extruderLayers[t] = new Set();
    }
  }

  let hasWipeTower = false;
  let inWipeTower = false;

  for (const line of lines) {
    const trimmed = line.trim();

    // Tool change
    const toolMatch = trimmed.match(/^T(\d+)/);
    if (toolMatch) {
      const newExtruder = parseInt(toolMatch[1]);
      if (newExtruder !== currentExtruder) toolChanges++;
      currentExtruder = newExtruder;
      ensureExtruder(currentExtruder);
      continue;
    }

    // Layer change
    if (trimmed === ';LAYER_CHANGE') {
      layerCount++;
      continue;
    }

    // Z height comment
    const zComment = trimmed.match(/^;Z:([\d.]+)/);
    if (zComment) {
      currentZ = parseFloat(zComment[1]);
      continue;
    }

    // Wipe tower detection
    if (trimmed === ';TYPE:Wipe tower') {
      hasWipeTower = true;
      inWipeTower = true;
      continue;
    }
    if (trimmed.startsWith(';TYPE:') && trimmed !== ';TYPE:Wipe tower') {
      inWipeTower = false;
      continue;
    }

    // G1 move with extrusion
    const g1Match = trimmed.match(/^G1\s(.+)/);
    if (!g1Match) continue;

    const params = g1Match[1];
    const xMatch = params.match(/X([\d.]+)/);
    const yMatch = params.match(/Y([\d.]+)/);
    const zMatch = params.match(/Z([\d.]+)/);
    const eMatch = params.match(/E([\d.]+)/);

    if (xMatch) currentX = parseFloat(xMatch[1]);
    if (yMatch) currentY = parseFloat(yMatch[1]);
    if (zMatch) currentZ = parseFloat(zMatch[1]);

    // Only count extrusion moves
    if (!eMatch) continue;

    ensureExtruder(currentExtruder);
    const b = extruderBounds[currentExtruder];
    b.minX = Math.min(b.minX, currentX);
    b.maxX = Math.max(b.maxX, currentX);
    b.minY = Math.min(b.minY, currentY);
    b.maxY = Math.max(b.maxY, currentY);
    b.minZ = Math.min(b.minZ, currentZ);
    b.maxZ = Math.max(b.maxZ, currentZ);

    extruderMoves[currentExtruder]++;
    extruderLayers[currentExtruder].add(currentZ);
  }

  // Build sorted layer arrays
  const sortedLayers = {};
  for (const [t, layers] of Object.entries(extruderLayers)) {
    sortedLayers[t] = [...layers].sort((a, b) => a - b);
  }

  // Legacy compat: t0/t1 fields
  ensureExtruder(0);
  ensureExtruder(1);

  return {
    bounds: { t0: extruderBounds[0], t1: extruderBounds[1] },
    extruderBounds,
    extruderMoves,
    extruderLayers: sortedLayers,
    t0Moves: extruderMoves[0] || 0,
    t1Moves: extruderMoves[1] || 0,
    layerCount,
    toolChanges,
    hasWipeTower,
    t1Layers: sortedLayers[1] || [],
  };
}

/**
 * Validate multi-color GCode output.
 *
 * Extends basic validation with: tool changes, per-extruder XY bounds,
 * extruder count, wipe/prime tower detection.
 *
 * @param {string} gcode - Raw GCode string
 * @param {object} [options] - Validation options
 * @param {number} [options.expectedExtruders=2] - Expected number of extruders used
 * @param {boolean} [options.requireWipeTower=true] - Whether wipe tower is expected
 * @returns {{ passed: boolean, checks: Array, extruderBounds: object, stats: object }}
 */
export function validateMulticolorGCode(gcode, options = {}) {
  const { expectedExtruders = 2, requireWipeTower = true } = options;

  // Run basic validation first
  const basic = validateGCode(gcode);
  const checks = [...basic.checks];
  let passed = basic.passed;

  function check(name, ok, detail) {
    checks.push({ name, passed: ok, detail });
    if (!ok) passed = false;
  }

  // Multi-color analysis
  const analysis = analyzeMulticolorGCode(gcode);

  // Check: Has tool changes
  check('has_tool_changes', analysis.toolChanges > 0,
    `${analysis.toolChanges} tool changes`);

  // Check: Expected number of extruders used
  const activeExtruders = Object.keys(analysis.extruderMoves)
    .filter(t => analysis.extruderMoves[t] > 0);
  check('extruder_count', activeExtruders.length >= expectedExtruders,
    `${activeExtruders.length} active extruders (expected ${expectedExtruders}): T${activeExtruders.join(', T')}`);

  // Check: Each expected extruder has moves
  for (let i = 0; i < expectedExtruders; i++) {
    const moves = analysis.extruderMoves[i] || 0;
    check(`t${i}_has_moves`, moves > 0, `T${i}: ${moves} extrusion moves`);
  }

  // Check: Wipe tower
  if (requireWipeTower) {
    check('has_wipe_tower', analysis.hasWipeTower,
      analysis.hasWipeTower ? 'Wipe tower extrusions found' : 'No wipe tower detected');
  } else {
    checks.push({ name: 'has_wipe_tower', passed: analysis.hasWipeTower,
      detail: analysis.hasWipeTower ? 'Wipe tower present' : 'No wipe tower (not required)' });
  }

  return {
    passed,
    checks,
    extruderBounds: analysis.extruderBounds,
    stats: {
      ...basic.stats,
      toolChanges: analysis.toolChanges,
      extruderMoves: analysis.extruderMoves,
      hasWipeTower: analysis.hasWipeTower,
      activeExtruders: activeExtruders.map(Number),
    },
  };
}

/**
 * Validate multi-object plate GCode output.
 *
 * Checks that the GCode contains geometry for multiple objects by analyzing
 * the XY print area extent. For N objects, the print area should be wider
 * than a single object (auto-arrange separates them).
 *
 * @param {string} gcode - Raw GCode string
 * @param {number} expectedObjects - Number of objects expected on the plate
 * @returns {{ passed: boolean, checks: Array, stats: object }}
 */
export function validatePlateGCode(gcode, expectedObjects) {
  // Run basic validation first
  const basic = validateGCode(gcode);
  const checks = [...basic.checks];
  let passed = basic.passed;

  function check(name, ok, detail) {
    checks.push({ name, passed: ok, detail });
    if (!ok) passed = false;
  }

  const lines = gcode.split('\n');

  // Collect all extrusion XY positions
  let currentX = 0, currentY = 0;
  const extrusionPositions = [];

  for (const line of lines) {
    const g1Match = line.match(/^G1\s(.+)/);
    if (!g1Match) continue;

    const params = g1Match[1];
    const xMatch = params.match(/X([\d.]+)/);
    const yMatch = params.match(/Y([\d.]+)/);
    const eMatch = params.match(/E([\d.]+)/);

    if (xMatch) currentX = parseFloat(xMatch[1]);
    if (yMatch) currentY = parseFloat(yMatch[1]);

    if (eMatch) {
      extrusionPositions.push({ x: currentX, y: currentY });
    }
  }

  // Compute overall print area (use reduce to avoid stack overflow on large arrays)
  let pMinX = Infinity, pMaxX = -Infinity, pMinY = Infinity, pMaxY = -Infinity;
  for (const p of extrusionPositions) {
    if (p.x < pMinX) pMinX = p.x;
    if (p.x > pMaxX) pMaxX = p.x;
    if (p.y < pMinY) pMinY = p.y;
    if (p.y > pMaxY) pMaxY = p.y;
  }
  const printArea = { minX: pMinX, maxX: pMaxX, minY: pMinY, maxY: pMaxY };
  const printWidth = pMaxX - pMinX;
  const printDepth = pMaxY - pMinY;

  check('has_print_area', printWidth > 0 && printDepth > 0,
    `Print area: ${printWidth.toFixed(1)} x ${printDepth.toFixed(1)}mm`);

  // For multiple objects, the print area should be larger than a single small object.
  // A single 10mm cube takes ~10mm. Two auto-arranged cubes should take >15mm in at least one axis.
  if (expectedObjects > 1) {
    const minExpectedSpan = 15; // mm — two small objects with spacing
    const hasMultipleRegions = printWidth > minExpectedSpan || printDepth > minExpectedSpan;
    check('multiple_object_spread', hasMultipleRegions,
      `Print span: ${printWidth.toFixed(1)}x${printDepth.toFixed(1)}mm (expected >${minExpectedSpan}mm for ${expectedObjects} objects)`);

    // More extrusion moves expected for multiple objects
    const minMovesPerObject = 100;
    check('sufficient_extrusion', basic.stats.extrusionMoves >= minMovesPerObject * expectedObjects,
      `${basic.stats.extrusionMoves} extrusion moves (expected >=${minMovesPerObject * expectedObjects} for ${expectedObjects} objects)`);
  }

  return {
    passed,
    checks,
    stats: {
      ...basic.stats,
      printArea,
      printWidth,
      printDepth,
      extrusionPositionCount: extrusionPositions.length,
    },
  };
}
